/**
 * Build step: precompile the source dictionaries (lib/i18n/zh.ts + en.ts) into
 * Lingui runtime catalogs at lib/i18n/locales/{locale}.ts.
 *
 * WHY A SMALL SCRIPT (and not the Lingui CLI / Vite plugin):
 * Lingui's CLI + @lingui/vite-plugin are built for the *macro* workflow, where
 * the message id is a HASH of the source text (`t`Welcome back``). This app uses
 * an EXPLICIT key namespace (`t('login.title')`) instead, so hashed catalogs
 * wouldn't resolve by key. For non-macro / key-based catalogs the Lingui
 * maintainers' recommended approach (js-lingui Discussion #1778) is to compile
 * messages yourself with `compileMessage` from `@lingui/message-utils`. That's
 * exactly what this does — we only orchestrate Lingui's OWN compiler, we don't
 * reimplement ICU parsing.
 *
 * Precompiling here means the ICU parser is dropped from the production bundle
 * (Lingui strips it in prod), while interpolation/plurals still work.
 *
 * Run via the `compile-catalogs` npm script (wired into dev/build/test/typecheck).
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { compileMessage } from '@lingui/message-utils/compileMessage'

import { zh } from '../lib/i18n/zh'
import enDict from '../lib/i18n/en'

const here = dirname(fileURLToPath(import.meta.url))
const outDir = join(here, '..', 'lib', 'i18n', 'locales')
mkdirSync(outDir, { recursive: true })

type Dict = Record<string, string | undefined>

function emit(locale: string, dict: Dict): void {
  const compiled: Record<string, unknown> = {}
  for (const [key, value] of Object.entries(dict)) {
    if (value == null) continue
    // compileMessage → a plain string (static) or a token array (dynamic/ICU).
    compiled[key] = compileMessage(value)
  }
  const body = `/* AUTO-GENERATED by scripts/compile-catalogs.ts — do not edit by hand. */
/* Precompiled Lingui catalog (explicit ids; ICU parser not needed at runtime). */
/* eslint-disable */
import type { Messages } from '@lingui/core'
export const messages: Messages = ${JSON.stringify(compiled)}
export default messages
`
  writeFileSync(join(outDir, `${locale}.ts`), body, 'utf8')
}

emit('zh', zh as Dict)
emit('en', enDict as Dict)

// eslint-disable-next-line no-console
console.log(`Compiled ${Object.keys(zh).length} messages → lib/i18n/locales/{zh,en}.ts`)
